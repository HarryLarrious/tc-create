#!/usr/bin/env python3
"""Writes tc/recipes_data.tc from Create's generated recipe files.

    python3 tools/gen_recipes.py <Create checkout>

Reads <checkout>/src/generated/resources/data/create/recipe/{pressing,milling,
splashing,haunting}/*.json (Create's data is under its MIT code license; its
assets are not used). Ingredient tags are resolved with TAGS below; recipes
whose ingredient or results name items this project does not have are left
out (results it does not have are dropped from a recipe that keeps others).
Mod-compat recipes (the compat/ folders) are skipped.

Each recipe becomes one string, "count id chance; ..." per result, keyed by
the ingredient id; milling also keeps its processing time.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "tc" / "recipes_data.tc"

# Create items the pack draws (pack/src/create_pack.py items()).
CREATE_ITEMS = {
    "iron_sheet", "golden_sheet", "copper_sheet", "brass_sheet", "wheat_flour", "cinder_flour",
    "dough", "andesite_alloy", "crushed_raw_iron", "crushed_raw_gold", "crushed_raw_copper", "zinc_nugget",
}

TAGS = {
    "c:ingots/iron": "minecraft:iron_ingot",
    "c:ingots/gold": "minecraft:gold_ingot",
    "c:ingots/copper": "minecraft:copper_ingot",
    "c:cobblestones": "minecraft:cobblestone",
    "minecraft:wool": "minecraft:white_wool",
    "c:sandstone/uncolored_blocks": "minecraft:sandstone",
    "minecraft:terracotta": "minecraft:terracotta",
}

KINDS = ("pressing", "milling", "splashing", "haunting")


def item_ok(i: str) -> bool:
    ns, _, name = i.partition(":")
    if ns == "minecraft":
        return True
    return ns == "create" and name in CREATE_ITEMS


def ingredient(ing) -> str | None:
    if isinstance(ing, list):
        ing = ing[0]
    if "item" in ing:
        return ing["item"]
    if "tag" in ing:
        return TAGS.get(ing["tag"])
    return None


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__)
        return 2
    base = Path(sys.argv[1]) / "src/generated/resources/data/create/recipe"
    tables: dict[str, dict[str, str]] = {k: {} for k in KINDS}
    times: dict[str, int] = {}
    skipped = 0
    for kind in KINDS:
        for path in sorted((base / kind).glob("*.json")):
            data = json.loads(path.read_text())
            ings = data.get("ingredients", [])
            if len(ings) != 1:
                skipped += 1
                continue
            src = ingredient(ings[0])
            if src is None or not item_ok(src):
                skipped += 1
                continue
            parts = []
            for r in data.get("results", []):
                rid = r.get("id") or r.get("item")
                if not rid or not item_ok(rid):
                    continue
                parts.append(f"{r.get('count', 1)} {rid} {r.get('chance', 1)}")
            if not parts:
                skipped += 1
                continue
            if src in tables[kind]:
                continue
            tables[kind][src] = "; ".join(parts)
            if kind == "milling":
                times[src] = int(data.get("processing_time", 100))

    lines = [
        "// Generated by tools/gen_recipes.py from Create's recipe data. Do not edit.",
        "// Each value is \"count id chance; ...\" per result.",
        "",
    ]
    for kind in KINDS:
        name = {"pressing": "pressRecipes", "milling": "millRecipes", "splashing": "washRecipes",
                "haunting": "hauntRecipes"}[kind]
        body = ", ".join(f'"{k}": "{v}"' for k, v in sorted(tables[kind].items()))
        lines += [f"/** {kind}: {len(tables[kind])} recipes. */", f"function {name}(): dict[str] {{",
                  f"    return {{{body}}};", "}", ""]
    body = ", ".join(f'"{k}": {v}' for k, v in sorted(times.items()))
    lines += ["/** Milling time per input (ticks at 16 RPM). */", "function millTimes(): dict[num] {",
              f"    return {{{body}}};", "}", ""]
    OUT.write_text("\n".join(lines))
    total = sum(len(t) for t in tables.values())
    print(f"wrote {OUT.relative_to(ROOT)}: {total} recipes ({skipped} skipped)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
